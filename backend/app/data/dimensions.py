def spread_target(total: float, weights: dict[str, float]) -> dict[str, float]:
    """把总额按权重拆分，保留 1 位小数。"""
    wsum = sum(weights.values())
    return {k: round(total * v / wsum, 1) for k, v in weights.items()}
